@inline function cast_from_fp(x::Float64)
 bits=reinterpret(UInt64,x);f=Float32(x);r1=reinterpret(Int32,UInt32(bits>>32))⊻reinterpret(Int32,UInt32(bits&UInt64(0xffffffff)));r2=UInt32(0);r3=Int64(0);r4=UInt64(0)
 r1⊻=double2int_rd(x)
