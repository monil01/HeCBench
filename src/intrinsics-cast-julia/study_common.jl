 r1⊻=float2int_rz(f)
 r1⊻=reinterpret(Int32,f)
 r2⊻=double2uint_rd(x)
 r2⊻=double2uint_rn(x)
 r2⊻=double2uint_ru(x)
 r2⊻=double2uint_rz(x)
 r2⊻=float2uint_rd(f)
 r2⊻=float2uint_rn(f)
 r2⊻=float2uint_ru(f)
 r2⊻=float2uint_rz(f)
 r2⊻=reinterpret(UInt32,f)
 r3⊻=double2ll_rd(x)
 r3⊻=double2ll_rn(x)
 r3⊻=double2ll_ru(x)
 r3⊻=double2ll_rz(x)
 r3⊻=float2ll_rd(f)
 r3⊻=float2ll_rn(f)
 r3⊻=float2ll_ru(f)
 r3⊻=float2ll_rz(f)
 r3⊻=reinterpret(Int64,x)
 r4⊻=double2ull_rd(x)
