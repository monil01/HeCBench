end
@inline function cast_to_fp(x::Int64)
 lo=reinterpret(UInt32,x%Int32);si=reinterpret(Int32,lo);ux=reinterpret(UInt64,x)
 r1=Float32(reinterpret(Float64,x));r2=Float64(si)+Float64(lo)
