   rho = Float64((elemMass[i+Int32(1)] / (volo[i+Int32(1)] * vnew[i+Int32(1)])))
   (qlin = (((-qlc_monoq) * rho) * (((delvxxi * (Float64(1.) - phixi)) + (delvxeta * (Float64(1.) - phieta))) + (delvxzeta * (Float64(1.) - phizeta)))))
   (qquad = ((qqc_monoq * rho) * ((((delvxxi * delvxxi) * (Float64(1.) - (phixi * phixi))) + ((delvxeta * delvxeta) * (Float64(1.) - (phieta * phieta)))) + ((delvxzeta * delvxzeta) * (Float64(1.) - (phizeta * phizeta))))))
  end
  (qq[i+Int32(1)] = qquad)
  (ql[i+Int32(1)] = qlin)
 end
 return nothing
end

@inline function applyMaterialPropertiesForElems_body!(ql,qq,delv,elemRep,elemElem,q,p,e,ss,v,vnewc,e_cut,p_cut,q_cut,v_cut,eosvmax,eosvmin,pmin,emin,rho0,numElem,gidx)
 @inbounds begin
  elem = Int32(((Int32(256) * div(gidx,Int32(256))) + rem(gidx,Int32(256))))
  if (elem >= numElem)
   return nothing
  end
  rep = Int32(elemRep[elem+Int32(1)])
  e_old = Float64(0.0)
  delvc = Float64(0.0)
  p_old = Float64(0.0)
  q_old = Float64(0.0)
  qq_old = Float64(0.0)
  ql_old = Float64(0.0)
  p_new = Float64(0.0)
  q_new = Float64(0.0)
  e_new = Float64(0.0)
  work = Float64(0.0)
  compression = Float64(0.0)
  compHalfStep = Float64(0.0)
  bvc = Float64(0.0)
  pbvc = Float64(0.0)
  pHalfStep = Float64(0.0)
  vchalf = Float64(0.0)
  vhalf = Float64(0.0)
  ssc = Float64(0.0)
  q_tilde = Float64(0.0)
  ssTmp = Float64(0.0)
  if (eosvmin != ZERO)
   if (vnewc[elem+Int32(1)] < eosvmin)
    (vnewc[elem+Int32(1)] = eosvmin)
   end
  end
  if (eosvmax != ZERO)
   if (vnewc[elem+Int32(1)] > eosvmax)
    (vnewc[elem+Int32(1)] = eosvmax)
   end
  end
  vc = Float64(v[elem+Int32(1)])
  if (eosvmin != ZERO)
   if (vc < eosvmin)
    (vc = eosvmin)
   end
  end
  if (eosvmax != ZERO)
   if (vc > eosvmax)
    (vc = eosvmax)
   end
  end
  vnewc_t = Float64(vnewc[elem+Int32(1)])
  e_temp = Float64(e[elem+Int32(1)])
  delv_temp = Float64(delv[elem+Int32(1)])
  p_temp = Float64(p[elem+Int32(1)])
  q_temp = Float64(q[elem+Int32(1)])
  qq_temp = Float64(qq[elem+Int32(1)])
  ql_temp = Float64(ql[elem+Int32(1)])
  j = Int32(Int32(0))
  while (j < rep)
   (e_old = e_temp)
   (delvc = delv_temp)
   (p_old = p_temp)
   (q_old = q_temp)
   (qq_old = qq_temp)
   (ql_old = ql_temp)
   (compression = ((ONE / vnewc_t) - ONE))
   (vchalf = (vnewc_t - (delvc * HALF)))
   (compHalfStep = ((ONE / vchalf) - ONE))
   if (vnewc_t <= eosvmin)
    (compHalfStep = compression)
   end
   if (vnewc_t >= eosvmax)
    (p_old = ZERO)
    (compression = ZERO)
    (compHalfStep = ZERO)
   end
   (work = ZERO)
   (e_new = ((e_old - ((HALF * delvc) * (p_old + q_old))) + (HALF * work)))
   if (e_new < emin)
    (e_new = emin)
   end
   (bvc = (C1S * (compHalfStep + ONE)))
   (pbvc = C1S)
   (pHalfStep = (bvc * e_new))
   if (abs(pHalfStep) < p_cut)
    (pHalfStep = ZERO)
   end
   if (vnewc_t >= eosvmax)
    (pHalfStep = ZERO)
   end
   if (pHalfStep < pmin)
    (pHalfStep = pmin)
   end
   (vhalf = (ONE / (ONE + compHalfStep)))
   if (delvc > ZERO)
    (q_new = ZERO)
   else
    (ssc = (((pbvc * e_new) + (((vhalf * vhalf) * bvc) * pHalfStep)) / rho0))
    if (ssc <= C1)
     (ssc = C2)
    else
     (ssc = sqrt(ssc))
    end
    (q_new = ((ssc * ql_old) + qq_old))
   end
   (e_new = (e_new + ((HALF * delvc) * ((THREE * (p_old + q_old)) - (FOUR * (pHalfStep + q_new))))))
   (e_new += (HALF * work))
   if (abs(e_new) < e_cut)
    (e_new = ZERO)
   end
   if (e_new < emin)
    (e_new = emin)
   end
   (bvc = (C1S * (compression + ONE)))
   (pbvc = C1S)
   (p_new = (bvc * e_new))
   if (abs(p_new) < p_cut)
    (p_new = ZERO)
   end
   if (vnewc_t >= eosvmax)
    (p_new = ZERO)
   end
   if (p_new < pmin)
    (p_new = pmin)
   end
   if (delvc > ZERO)
    (q_tilde = ZERO)
   else
    ssc = Float64((((pbvc * e_new) + (((vnewc_t * vnewc_t) * bvc) * p_new)) / rho0))
    if (ssc <= C1)
     (ssc = C2)
    else
     (ssc = sqrt(ssc))
    end
    (q_tilde = ((ssc * ql_old) + qq_old))
   end
   (e_new = (e_new - (((((SEVEN * (p_old + q_old)) - (EIGHT * (pHalfStep + q_new))) + (p_new + q_tilde)) * delvc) * SIXTH)))
   if (abs(e_new) < e_cut)
    (e_new = ZERO)
   end
   if (e_new < emin)
    (e_new = emin)
   end
   (bvc = (C1S * (compression + ONE)))
   (pbvc = C1S)
   (p_new = (bvc * e_new))
   if (abs(p_new) < p_cut)
    (p_new = ZERO)
   end
   if (vnewc_t >= eosvmax)
    (p_new = ZERO)
   end
   if (p_new < pmin)
    (p_new = pmin)
   end
   if (delvc <= ZERO)
    (ssc = (((pbvc * e_new) + (((vnewc_t * vnewc_t) * bvc) * p_new)) / rho0))
    if (ssc <= C1)
     (ssc = C2)
    else
     (ssc = sqrt(ssc))
    end
    (q_new = ((ssc * ql_old) + qq_old))
    if (abs(q_new) < q_cut)
     (q_new = ZERO)
    end
   end
   j += Int32(1)
  end
  (p[elem+Int32(1)] = p_new)
  (e[elem+Int32(1)] = e_new)
  (q[elem+Int32(1)] = q_new)
  (ssTmp = (((pbvc * e_new) + (((vnewc_t * vnewc_t) * bvc) * p_new)) / rho0))
  if (ssTmp <= C1)
   (ssTmp = C2)
  else
   (ssTmp = sqrt(ssTmp))
  end
  (ss[elem+Int32(1)] = ssTmp)
  if (abs((vnewc_t - ONE)) < v_cut)
   (vnewc_t = ONE)
  end
  (v[elem+Int32(1)] = vnewc_t)
 end
 return nothing
end

