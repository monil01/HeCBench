_RSBOX = bytes([_SBOX.index(i) for i in range(256)])


@triton.jit
def aes_lite_kernel(inp_ptr, out_ptr, key_ptr, sbox_ptr, N, BLOCK: tl.constexpr):
    """One 'AES-lite' round: out[i] = sbox[in[i] ^ key[i & 15]]."""
    pid = tl.program_id(0)
    offs = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offs < N
    inp = tl.load(inp_ptr + offs, mask=mask, other=0)
    k = tl.load(key_ptr + (offs & 15), mask=mask, other=0)
    x = inp ^ k
    s = tl.load(sbox_ptr + x.to(tl.int32), mask=mask, other=0)
    tl.store(out_ptr + offs, s, mask=mask)


def cpu_reference(inp, key, sbox):
    x = (inp.astype("int32") ^ key[torch.arange(len(inp)) & 15].numpy().astype("int32")).astype("uint8")
    return sbox[x]


def main():
    if len(sys.argv) < 3:
        print(f"Usage: {sys.argv[0]} <iterations> <0 or 1> <path to bitmap image file>")
        print("0=encrypt, 1=decrypt")
        return 1
    iterations = int(sys.argv[1])
    decrypt = bool(int(sys.argv[2]))
    # Bitmap file path is ignored — we synthesize the input.

    width, height = 512, 512
    print(f"Image width and height: {width} {height}")

    import numpy as np
    N = width * height
    torch.manual_seed(123)
    input_bytes = torch.randint(0, 256, (N,), dtype=torch.uint8, device="cuda")
    output_bytes = torch.zeros_like(input_bytes)
    key = torch.randint(0, 256, (16,), dtype=torch.uint8, device="cuda")

    sbox_t = torch.tensor(list(_SBOX), dtype=torch.uint8, device="cuda")
    rsbox_t = torch.tensor(list(_RSBOX), dtype=torch.uint8, device="cuda")
    which = rsbox_t if decrypt else sbox_t

    print(f"Executing kernel for {iterations} iterations")
    print("-------------------------------------------")

    BLOCK = 1024
    grid = ((N + BLOCK - 1) // BLOCK,)

    torch.cuda.synchronize()
    t0 = time.perf_counter()
    for _ in range(iterations):
        aes_lite_kernel[grid](input_bytes, output_bytes, key, which, N, BLOCK=BLOCK)
    torch.cuda.synchronize()
    dt_s = (time.perf_counter() - t0) / iterations
    print(f"Average kernel execution time {dt_s:f} (s)")

    # CPU reference
    inp = input_bytes.cpu().numpy()
    k_np = key.cpu().numpy()
    tbl = np.frombuffer(_RSBOX if decrypt else _SBOX, dtype=np.uint8)
    idx = np.arange(N, dtype=np.int64) & 15
    x = (inp.astype(np.int32) ^ k_np[idx].astype(np.int32)).astype(np.uint8)
    verif = tbl[x]

    ok = bool(np.array_equal(output_bytes.cpu().numpy(), verif))
    print("Pass" if ok else "Fail")
    print("PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
